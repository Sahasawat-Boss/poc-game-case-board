/** เอาชื่อคนของรอบเล่นนี้ไปแทน {{nameN}} ในข้อความ */
function applyNames(text: string, names: string[]): string {
  return text.replace(/\{\{name(\d+)\}\}/g, (_, id: string) => {
    const full = names[Number(id) - 1];
    return full ? `<b>${full}</b>` : `คนที่ ${id}`;
  });
}

/**
 * ประกอบคดีทั้งหมดสำหรับรอบเล่นหนึ่ง
 * แทนชื่อคนและชื่อสถานที่ให้ตรงกับชุดที่สุ่มไว้ในฐานข้อมูลรอบนี้
 */
export function buildCases(names: string[], places: PlaceMap): GameCase[] {
  const text = (s: string) => applyPlaces(applyNames(s, names), places);

  return TEMPLATES.map((t) => {
    const answer =
      t.answer.kind === "choice"
        ? {
            kind: "choice" as const,
            prompt: text(t.answer.prompt),
            options: t.answer.options.map((o) => applyPlaces(o, places)),
            correct: applyPlaces(t.answer.correct, places),
          }
        : t.answer;

    return {
      ...t,
      brief: text(t.brief),
      goal: text(t.goal),
      hints: t.hints.map(text),
      answer,
    };
  });
}

/** ชุดคดีเริ่มต้น ใช้ตอนเรนเดอร์ฝั่งเซิร์ฟเวอร์ที่ยังไม่ได้สุ่มอะไร */
export const DEFAULT_CASES = buildCases(DEFAULT_NAMES, DEFAULT_PLACES);

/** เครื่องมือที่ปลดล็อกแล้ว ณ คดีที่ n (สะสมจากคดีก่อนหน้าทั้งหมด) */
export function toolsUnlockedAt(cases: GameCase[], n: number): Set<string> {
  const tools = new Set<string>();
  for (const c of cases) {
    if (c.n > n) break;
    for (const t of c.unlocks ?? []) tools.add(t);
  }
  return tools;
}
